package javapractice.classandobjectspart2;

public class ConstructorsIntro {

    /*

        - A special method that every class must have.
        - Used for creating objects of the classes.
        - The execution of a constructor always depends on the object.

        - Constructor is a special method that matches the name of the class
          and has no return type nor a specifier.

        - No-Argument Constructor: A Constructor that has no parameters.
        - Parametrized Constructor: A Constructor that has parameters.

        - Multiple constructors can be declared in a class by implementing
          the Method Overloading principle.

     */

}